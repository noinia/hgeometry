-- | Given a name and a map of colors, construct an ipe style
createIpeStyle             :: IpeWriteText r
                           => Text -- ^ the name of the stylesheet
                           -> Map.Map Text (IpeValue (RGB r)) -> IpeStyle
createIpeStyle name colors = IpeStyle (Just name) xml
  where
    xml = Element "ipestyle" [("name",name)] (Map.foldMapWithKey mkXml colors)
    mkXml color = \case
      Named _  -> []
      Valued v -> case ipeWriteText v of
        Just t  -> [ Element "color" [("name",color),("value",t)] [] ]
        Nothing -> []

-- | Helper for just producing a set of names
namedSet :: Map.Map Text v -> Set.Set (IpeColor r)
namedSet = Set.mapMonotonic named . Map.keysSet



-- | Defines all colors with their RGB value as defined in the colors.isy style file that
-- comes with ipe
allColors :: Fractional r => Map.Map Text (IpeValue (RGB r))
allColors = allColorsWith $ \r g b -> Valued (RGB (realToFrac r) (realToFrac g) (realToFrac b))

