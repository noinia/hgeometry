-- | only the non-repeated names; i.e. the ones without numerical suffix.
nonRepeated :: Map.Map Text v -> Map.Map Text v
nonRepeated = Map.filterWithKey (\name _ -> case Text.unsnoc name of
                                         Nothing    -> True
                                         Just (_,c) -> not $ isNumber c
                                     )
-- | A map with all colors
allColorNames :: Map.Map Text ()
allColorNames = allColorsWith $ \_ _ _ -> ()

